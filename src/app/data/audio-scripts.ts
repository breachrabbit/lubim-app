/**
 * Возвращает длительность произнесения текста в секундах (приблизительно).
 * Основано на средней скорости чтения диктора ~140 слов в минуту для русского языка.
 * Используется для отображения времени в плеере до загрузки файла.
 */
export function estimateDuration(text: string): number {
  const words = text.trim().split(/\s+/).length;
  const wordsPerSecond = 140 / 60; // ~2.33 слова в секунду
  return Math.round(words / wordsPerSecond);
}

/**
 * Возвращает пути к аудиофайлам для указанного места, если для него есть сценарий.
 * Соглашение: MP3 лежат в /public/audio/{male,female}/{slug}.mp3
 *
 * Если файлов ещё нет физически — HTML5-аудио просто не загрузит их,
 * и плеер покажет состояние ошибки (или скроется, если оба отсутствуют).
 * Это нормально: достаточно сгенерировать файлы и положить на место —
 * плеер заработает без изменений кода.
 */
export function getAudioPaths(slug: string): {
  male?: string;
  female?: string;
  durationSeconds?: number;
} {
  const script = audioScripts[slug];
  if (!script) {
    return {};
  }
  return {
    male: `/audio/male/${slug}.mp3`,
    female: `/audio/female/${slug}.mp3`,
    durationSeconds: estimateDuration(script.fullText),
  };
}
